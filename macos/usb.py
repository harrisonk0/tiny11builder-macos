"""Prepare UEFI/FAT32 installer files without erasing or writing a USB device."""
import json
from pathlib import Path
import plistlib
import re
import shutil
import subprocess
import stat


def run(args, capture=False):
    values = [str(arg) for arg in args]
    if values[0] == 'wimlib-imagex' and shutil.which('taskpolicy'):
        values = ['taskpolicy', '-b', 'nice', '-n', '19', *values]
    try:
        result = subprocess.run(values, check=True, text=True, capture_output=capture)
    except subprocess.CalledProcessError as exc:
        raise RuntimeError(f'USB image operation stopped or failed ({exc.returncode}); staging retained') from exc
    return result.stdout


def prepare(args):
    iso = Path(args.source).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()
    scratch = Path(args.scratch).expanduser().resolve()
    if not iso.is_file():
        raise RuntimeError('Installer ISO not found')
    if getattr(iso.stat(), 'st_flags', 0) & getattr(stat, 'SF_DATALESS', 0x40000000):
        raise RuntimeError('ISO contents are offloaded. In Finder choose Download Now/Keep Downloaded first.')
    if output.exists() or scratch.exists():
        raise RuntimeError('Output and scratch directories must be new')
    if scratch in output.parents or output in scratch.parents or output == scratch:
        raise RuntimeError('Output and scratch must be separate directories')
    for tool in ('wimlib-imagex', 'hdiutil'):
        if not shutil.which(tool):
            raise RuntimeError(f'Missing prerequisite: {tool}')
    if shutil.disk_usage(iso.parent).free < 17 * 1024**3:
        raise RuntimeError('Allow at least 17 GiB free for temporary LZX conversion and USB files')
    attached = run(['hdiutil', 'attach', '-readonly', '-nobrowse', '-plist', iso], capture=True)
    mount = next(Path(entry['mount-point']) for entry in plistlib.loads(attached.encode())['system-entities']
                 if 'mount-point' in entry)
    try:
        image = mount / 'sources/install.wim'
        for path in (image, mount / 'sources/boot.wim', mount / 'efi/boot/bootx64.efi'):
            if path.is_file() and getattr(path.stat(), 'st_flags', 0) & getattr(stat, 'SF_DATALESS', 0x40000000):
                raise RuntimeError(f'{path.name} is offloaded. In Finder choose Download Now/Keep Downloaded first.')
        info = run(['wimlib-imagex', 'info', image], capture=True)
        if not re.search(r'(?m)^Image Count:\s*1\s*$', info):
            raise RuntimeError('USB preparation expects the single-edition image generated by build')
        if not re.search(r'(?im)^\s*Architecture:\s*(amd64|x64|x86_64)\s*$', info):
            raise RuntimeError('Installer is not x64')
        if not (mount / 'efi/boot/bootx64.efi').is_file():
            raise RuntimeError('x64 removable-media EFI loader is missing')
        scratch.mkdir(parents=True)
        # The ISO-only boot catalog may have mode 000; UEFI USB boot uses EFI/BOOT.
        shutil.copytree(mount, output, ignore=shutil.ignore_patterns('install.wim', 'install.esd', 'boot.catalog'))
        for entry in output.rglob('*'):
            entry.chmod(0o755 if entry.is_dir() else 0o644)
        output.chmod(0o755)
        normal = scratch / 'install.wim'
        # wimlib refuses to split solid LZMS resources: export non-solid LZX first.
        run(['wimlib-imagex', 'export', image, '1', normal, '--compress=LZX', '--threads=1'])
        first = output / 'sources/install.swm'
        run(['wimlib-imagex', 'split', normal, first, '3800'])
        run(['wimlib-imagex', 'verify', first, '--ref=' + str(output / 'sources/install*.swm')])
        too_large = [str(path) for path in output.rglob('*') if path.is_file() and path.stat().st_size >= 2**32]
        if too_large:
            raise RuntimeError('FAT32-incompatible files: ' + ', '.join(too_large))
        parts = sorted(output.glob('sources/install*.swm'))
        if not parts:
            raise RuntimeError('No split WIM parts generated')
        metadata = run(['wimlib-imagex', 'info', first, '1'], capture=True)
        original_metadata = run(['wimlib-imagex', 'info', image, '1'], capture=True)
        # Compression and resource location change; all image properties must match.
        if metadata != original_metadata:
            raise RuntimeError('Edition metadata changed during USB conversion')
        report = {'source_iso': str(iso), 'uefi_files_prepared': True, 'split_wim_verified': True,
                  'all_files_fit_fat32': True, 'firmware_boot_verified': False,
                  'parts': [{'name': path.name, 'bytes': path.stat().st_size} for path in parts],
                  'total_bytes': sum(path.stat().st_size for path in output.rglob('*') if path.is_file())}
        output.with_name(output.name + '.report.json').write_text(json.dumps(report, indent=2))
        normal.unlink()
        print(f'USB files prepared: {output}\nCopy the folder contents to a FAT32 USB and boot its UEFI entry.')
        return 0
    finally:
        run(['hdiutil', 'detach', mount])
